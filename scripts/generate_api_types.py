"""Generate the dashboard's response types from Leash's FastAPI OpenAPI schema."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from leash.api import app

SCHEMAS = (
    "ActionKind",
    "AuditRecord",
    "BenchmarkConfigurationView",
    "BenchmarkSummaryView",
    "Decision",
    "HealthResponse",
    "ImpactPreview",
    "LatencySummary",
    "PendingReviewView",
    "SecretFinding",
    "TelemetrySummary",
    "Verdict",
    "VerdictSource",
)
OUTPUT = Path(__file__).resolve().parents[1] / "apps" / "dashboard" / "src" / "generated-api.ts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return repr(schema["const"]).replace("'", '"')
    if "enum" in schema:
        return " | ".join(repr(value).replace("'", '"') for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"{ts_type(schema['items'])}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if extra is True:
            return "Record<string, unknown>"
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    raise ValueError(f"Unsupported OpenAPI schema shape: {schema}")


def generate() -> str:
    components = app.openapi()["components"]["schemas"]
    lines = [
        "// Generated by scripts/generate_api_types.py from FastAPI OpenAPI. Do not edit.",
        "// Response defaults are serialized by FastAPI, so response fields are required here.",
        "",
    ]
    for name in SCHEMAS:
        schema = components[name]
        if schema.get("type") != "object":
            lines.append(f"export type {name} = {ts_type(schema)};")
            lines.append("")
            continue
        lines.append(f"export interface {name} {{")
        for property_name, property_schema in schema["properties"].items():
            lines.append(f"  {property_name}: {ts_type(property_schema)};")
        lines.extend(("}", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated types are stale")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Dashboard API types are stale; run scripts/generate_api_types.py")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
